-- 1. Таблиця та тестові записи (SQL Editor у Supabase)
create table if not exists public.games (
  id bigint generated by default as identity primary key,
  title text not null,
  genre text not null,
  players smallint not null default 2,
  created_at timestamptz not null default now()
);

alter table public.games enable row level security;

insert into public.games (title, genre, players)
values
  ('Каркассон', 'Стратегія', 4),
  ('Монополія', 'Економічна', 6),
  ('Uno', 'Карткова', 10),
  ('Дженга', 'Динамічна', 8),
  ('Шахи', 'Логічна', 2);

-- 2. Дозвіл на читання
grant select on table public.games to anon;

create policy "Public can read games"
on public.games
for select
to anon
using (true);

-- 3. Обмеження довжини та дозвіл на додавання
alter table public.games
add constraint games_title_length
check (char_length(trim(title)) between 1 and 150);

alter table public.games
add constraint games_genre_length
check (char_length(trim(genre)) between 1 and 150);

alter table public.games
add constraint games_players_range
check (players between 1 and 99);

grant insert (title, genre, players)
on table public.games
to anon;

create policy "Public can add games"
on public.games
for insert
to anon
with check (true);
